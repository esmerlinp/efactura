def is_valid_nationality_code(code) -> bool:
    """True si el código es una nacionalidad oficial SIRLA."""
    return str(code or "").strip() in _NATIONALITY_BY_CODE


def get_nationality_name(code) -> str:
    """Devuelve el nombre de la nacionalidad oficial, o '' si no existe."""
    return _NATIONALITY_BY_CODE.get(str(code or "").strip(), "")


def nationality_to_sirla(nationality) -> str:
    """Convierte el ID de nacionalidad al valor SIRLA de 3 posiciones.

    La nacionalidad dominicana (1) se omite (cadena vacía). Los extranjeros se
    emiten como AN de 3 posiciones, ej. 2 -> "2  ", 29 -> "29 ", 155 -> "155".
    """
    val = str(nationality or "").strip()
    if not val or val == "1":
        return ""
    return val[:3]
